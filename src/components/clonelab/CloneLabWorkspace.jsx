import React, { useState } from 'react';
import { clonelabAPI } from '../../services/clonelabApi';
import AssayComparison from './AssayComparison';
import PlasmidMap from './PlasmidMap';
import VirtualGel from './VirtualGel';
import '../../styles/CloneLab.css';

const clean = (value) => value.replace(/\s/g, '').toUpperCase();

export default function CloneLabWorkspace() {
  const [vector, setVector] = useState('');
  const [insert, setInsert] = useState('');
  const [position, setPosition] = useState(0);
  const [enzymes, setEnzymes] = useState('EcoRI, BamHI, HindIII, XhoI');
  const [hypotheses, setHypotheses] = useState([]);
  const [optimization, setOptimization] = useState(null);
  const [gel, setGel] = useState(null);
  const [observed, setObserved] = useState('');
  const [interpretation, setInterpretation] = useState(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState(null);
  const [demo, setDemo] = useState(null);

  const loadDemo = async (demonstrationId) => {
    setLoading(true); setError(null); setInterpretation(null);
    try {
      const result = await clonelabAPI.loadDemonstration(demonstrationId);
      setVector(result.vector.sequence);
      setInsert(result.promoter.sequence);
      setPosition(result.insertion_start);
      setEnzymes(result.demonstration.candidate_enzymes.join(', '));
      setHypotheses(result.analysis.hypotheses);
      setOptimization(result.analysis.optimization);
      setGel(result.analysis.gel);
      setDemo(result);
    } catch (err) { setError(err.message); } finally { setLoading(false); }
  };

  const analyze = async () => {
    setLoading(true); setError(null); setOptimization(null); setGel(null); setInterpretation(null);
    try {
      const states = await clonelabAPI.generateHypotheses({
        vector: { name: 'Vector', sequence: clean(vector), topology: 'circular' },
        insert: { name: 'Insert', sequence: clean(insert), topology: 'linear' },
        insertion_start: Number(position), include_tandem: true,
      });
      setHypotheses(states.hypotheses);
      const result = await clonelabAPI.optimizeDigest({
        hypotheses: states.hypotheses.map((state) => ({
          name: state.label, hypothesis_id: state.hypothesis_id, label: state.label,
          sequence: state.sequence, topology: state.topology,
        })),
        candidate_enzymes: enzymes.split(',').map((name) => name.trim()).filter(Boolean),
        min_fragment_bp: 25, max_fragment_bp: 20000, top: 12,
      });
      setOptimization(result);
      const predictions = result.best_digest.predictions;
      setGel(await clonelabAPI.simulateGel({
        lanes: Object.entries(predictions).map(([id, prediction]) => ({
          lane_id: id, label: prediction.label, fragment_lengths: prediction.fragment_lengths,
          uncut_circular: prediction.uncut,
        })),
        ladder: 'neb_1kb_plus_n0550', calibration_id: 'neb_n0550_1pct_tbe_image_v1', min_visible_bp: 25,
      }));
    } catch (err) { setError(err.message); } finally { setLoading(false); }
  };

  const interpret = async () => {
    setError(null);
    try {
      const values = observed.split(',').map((value) => Number(value.trim())).filter(Number.isFinite);
      const predictions = Object.fromEntries(Object.entries(optimization.best_digest.predictions)
        .map(([id, prediction]) => [id, prediction.visible_signature.filter(Number.isFinite)]));
      setInterpretation(await clonelabAPI.interpretResults({ observed_bands_bp: values, predictions }));
    } catch (err) { setError(err.message); }
  };

  const downloadReport = async () => {
    try {
      const report = await clonelabAPI.exportReport({
        project: { name: 'Standalone CloneLab analysis', project_id: 'stateless' },
        analysis: { hypotheses, optimization, gel, interpretation }, output_format: 'markdown',
      });
      const url = URL.createObjectURL(new Blob([report.content], { type: report.media_type }));
      const link = document.createElement('a'); link.href = url; link.download = 'clonelab-report.md'; link.click();
      URL.revokeObjectURL(url);
    } catch (err) { setError(err.message); }
  };

  return (
    <main className="clonelab-workspace">
      <header className="clonelab-hero">
        <div><div className="clonelab-kicker">DARWIN / MOLECULAR VALIDATION</div>
          <h1>CloneLab</h1><p>Turn explicit DNA construct hypotheses into a diagnostic experiment that distinguishes molecular outcomes.</p></div>
        <div className="clonelab-engine-note"><strong>Deterministic engine</strong><span>Sequences, cut sites, fragments, and rankings are calculated by code, not generated by an LLM.</span></div>
      </header>
      <section className="clonelab-panel clonelab-input-panel">
        <div className="clonelab-panel-heading"><div><span className="clonelab-step">01</span><h2>Define the molecular design</h2></div></div>
        <div className="clonelab-demo-picker">
          <div><strong>Release demonstrations</strong><span>Load an atlas target, genome-derived promoter, authenticated pUC19 vector, and optimized assay.</span></div>
          <button disabled={loading} onClick={() => loadDemo('arabidopsis_clock')}>Arabidopsis / CCA1</button>
          <button disabled={loading} onClick={() => loadDemo('petunia_pigmentation')}>Petunia / AN2</button>
        </div>
        {demo && <div className="clonelab-demo-context">
          <div><span>ATLAS TARGET</span><strong>{demo.demonstration.gene_symbol} · {demo.demonstration.species}</strong></div>
          <p>{demo.demonstration.hypothesis}</p>
          <p>{demo.demonstration.boundary}</p>
          <code>{demo.promoter.record_id}:{demo.promoter.interval.start.toLocaleString()}-{demo.promoter.interval.end.toLocaleString()} · {demo.promoter.length.toLocaleString()} bp · {demo.promoter.sequence_sha256.slice(0, 12)}…</code>
        </div>}
        <div className="clonelab-sequence-grid">
          <label><span>Circular vector sequence</span><textarea value={vector} onChange={(e) => setVector(e.target.value)} placeholder="Paste vector DNA (FASTA header optional only through import API)" /></label>
          <label><span>Linear insert sequence</span><textarea value={insert} onChange={(e) => setInsert(e.target.value)} placeholder="Paste insert DNA" /></label>
        </div>
        <div className="clonelab-controls">
          <label><span>Insertion coordinate [0, vector length]</span><input type="number" min="0" max={clean(vector).length} value={position} onChange={(e) => setPosition(e.target.value)} /></label>
          <label className="clonelab-enzyme-input"><span>Candidate enzymes, comma separated</span><input value={enzymes} onChange={(e) => setEnzymes(e.target.value)} /></label>
          <button className="clonelab-run" disabled={loading || !vector || !insert} onClick={analyze}>{loading ? 'Calculating…' : 'Optimize diagnostic digest'}</button>
        </div>
        {error && <div className="clonelab-error">{error}</div>}
      </section>
      {hypotheses.length > 0 && <section className="clonelab-panel">
        <div className="clonelab-panel-heading"><div><span className="clonelab-step">02</span><h2>Sequence-complete hypotheses</h2></div></div>
        <div className="clonelab-map-grid">{hypotheses.map((state) => <PlasmidMap
          key={state.hypothesis_id}
          construct={state}
          digest={optimization?.best_digest?.predictions?.[state.hypothesis_id]}
        />)}</div>
      </section>}
      <AssayComparison optimization={optimization} />
      <VirtualGel gel={gel} />
      {optimization && <section className="clonelab-panel">
        <div className="clonelab-panel-heading"><div><span className="clonelab-step">05</span><h2>Interpret observed bands</h2></div></div>
        <div className="clonelab-controls">
          <label className="clonelab-enzyme-input"><span>Measured fragment sizes in bp, comma separated</span>
            <input value={observed} onChange={(event) => setObserved(event.target.value)} placeholder="800, 200" /></label>
          <button className="clonelab-run" disabled={!observed} onClick={interpret}>Compare hypotheses</button>
          <button className="clonelab-report-button" onClick={downloadReport}>Download report</button>
        </div>
        {interpretation && <div className={`clonelab-interpretation ${interpretation.ambiguous ? 'ambiguous' : 'matched'}`}>
          <strong>{interpretation.compatible_hypotheses.length === 1
            ? `Compatible state: ${interpretation.compatible_hypotheses[0]}`
            : interpretation.compatible_hypotheses.length > 1
              ? `Ambiguous: ${interpretation.compatible_hypotheses.join(', ')}`
              : 'No tested state fully matches'}</strong>
          <span>{interpretation.interpretation_boundary}</span>
        </div>}
      </section>}
    </main>
  );
}
