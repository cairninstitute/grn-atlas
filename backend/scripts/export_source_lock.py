#!/usr/bin/env python3
"""Export source_import_runs to a committed lock file for reproducibility.

The lock file captures, per source, the sha256 of its inputs at the time of
the last successful build. A subsequent build can verify its own inputs against
the lock and fail loudly if anything drifted.

Usage:
    venv/bin/python backend/scripts/export_source_lock.py                      # export
    venv/bin/python backend/scripts/export_source_lock.py --check              # verify
    venv/bin/python backend/scripts/export_source_lock.py --check --warn-only  # verify without failing
"""
from __future__ import annotations

import argparse
import json
import sqlite3
import sys
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[1]
DB = BACKEND / "data" / "grn.sqlite3"
LOCK_FILE = BACKEND / "data" / "sources.lock.json"

REDISTRIBUTION = {
    "AGRIS AtRegNet": "academic",
    "AGRIS AtRegNet expanded": "academic",
    "ATRM": "academic",
    "ChIP-Atlas": "cc-by-4.0",
    "Cistrome": "verify-only",
    "CollecTRI": "verify-only",
    "ConnecTF experiment evidence": "academic",
    "Conserved signed orthology": "derived",
    "DirectBinding": "mixed",
    "Expression Atlas reviewed perturbations": "cc-by-4.0",
    "GRASSIUS": "verify-only",
    "PCBase 2.0": "verify-only",
    "Perturbation sign consensus": "derived",
    "PlantTFDB": "academic",
    "ReMap": "cc-by-4.0",
    "SIGNOR": "cc-by-sa-4.0",
    "TFLink small-scale": "cc-by-4.0",
    "UniBind": "cc-by-4.0",
}


def export_lock(db_path: Path, lock_path: Path) -> dict:
    conn = sqlite3.connect(f"file:{db_path}?mode=ro", uri=True)
    conn.row_factory = sqlite3.Row
    rows = conn.execute(
        "SELECT source_name, source_version, source_url, sha256, status, counts "
        "FROM source_import_runs WHERE status='complete' "
        "ORDER BY source_name, source_version"
    ).fetchall()
    conn.close()

    sources = {}
    for row in rows:
        key = f"{row['source_name']}|{row['source_version']}"
        entry = {
            "source_name": row["source_name"],
            "source_version": row["source_version"],
            "source_url": row["source_url"],
            "sha256": row["sha256"],
            "status": row["status"],
        }
        counts = json.loads(row["counts"]) if row["counts"] else {}
        if counts:
            entry["counts"] = counts
        redist = REDISTRIBUTION.get(row["source_name"])
        if redist:
            entry["redistribution"] = redist
        sources[key] = entry

    lock = {
        "_comment": "Auto-generated by export_source_lock.py. Do not edit by hand.",
        "sources": sources,
    }
    lock_path.write_text(json.dumps(lock, indent=2, sort_keys=True) + "\n")
    print(f"Exported {len(sources)} source entries to {lock_path}")
    return lock


def check_lock(db_path: Path, lock_path: Path, warn_only: bool = False) -> int:
    if not lock_path.exists():
        print(f"SKIP: no lock file at {lock_path}")
        return 0

    lock = json.loads(lock_path.read_text())
    expected = lock.get("sources", {})
    if not expected:
        print("SKIP: lock file is empty")
        return 0

    conn = sqlite3.connect(f"file:{db_path}?mode=ro", uri=True)
    conn.row_factory = sqlite3.Row
    rows = conn.execute(
        "SELECT source_name, source_version, sha256 "
        "FROM source_import_runs WHERE status='complete'"
    ).fetchall()
    conn.close()

    actual = {}
    for row in rows:
        key = f"{row['source_name']}|{row['source_version']}"
        actual[key] = row["sha256"]

    errors = []
    warnings = []
    pinned = 0
    matched = 0

    for key, entry in sorted(expected.items()):
        exp_hash = entry.get("sha256")
        if exp_hash is None:
            warnings.append(f"  {key}: no hash in lock (unpinned)")
            continue
        pinned += 1
        act_hash = actual.get(key)
        if act_hash is None:
            errors.append(f"  {key}: MISSING from build (expected sha256={exp_hash[:16]}...)")
        elif act_hash != exp_hash:
            errors.append(
                f"  {key}: DRIFT\n"
                f"    expected: {exp_hash}\n"
                f"    actual:   {act_hash}"
            )
        else:
            matched += 1

    new_sources = set(actual.keys()) - set(expected.keys())

    print(f"Lock check: {matched}/{pinned} pinned sources match")
    if warnings:
        print(f"Unpinned ({len(warnings)}):")
        for w in warnings:
            print(w)
    if new_sources:
        print(f"New sources not in lock ({len(new_sources)}):")
        for s in sorted(new_sources):
            print(f"  {s}")
    if errors:
        label = "WARNING" if warn_only else "ERROR"
        print(f"\n{label}: {len(errors)} source(s) drifted or missing:")
        for e in errors:
            print(e)
        if not warn_only:
            return 1
    elif not errors and not warnings:
        print("All pinned sources verified.")

    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--db", type=Path, default=DB)
    parser.add_argument("--lock", type=Path, default=LOCK_FILE)
    parser.add_argument("--check", action="store_true",
                        help="Verify current build against the lock file")
    parser.add_argument("--warn-only", action="store_true",
                        help="Print drift as warnings instead of failing")
    args = parser.parse_args()

    if args.check:
        return check_lock(args.db, args.lock, warn_only=args.warn_only)
    else:
        export_lock(args.db, args.lock)
        return 0


if __name__ == "__main__":
    raise SystemExit(main())
