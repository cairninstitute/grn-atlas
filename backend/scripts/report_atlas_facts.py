#!/usr/bin/env python3
"""Generate the atlas's own numbers, so documentation can cite rather than retype.

Every count in README.md, ROADMAP.md and the analysis docs was typed by hand at
some point and then drifted: the README claimed ~1,470,000 interactions against
an actual 4.2M, and its validation table disagreed with the per-species JSON it
was derived from. Hand-typed figures always drift; the fix is to stop typing
them.

This writes docs/ATLAS_FACTS.md and backend/data/atlas_facts.json from the
database itself. Documentation links to the first; anything automated reads the
second. Both carry an as-of date and the core content digest, so a figure can
always be traced to the build that produced it.

Read-only.

Usage:
    venv/bin/python backend/scripts/report_atlas_facts.py
    venv/bin/python backend/scripts/report_atlas_facts.py --emit-floors
"""
from __future__ import annotations

import argparse
import json
import sqlite3
import sys
from datetime import datetime, timezone
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[1]
ROOT = BACKEND.parent
DB = BACKEND / "data" / "grn.sqlite3"
MD = ROOT / "docs" / "ATLAS_FACTS.md"
JSON_OUT = BACKEND / "data" / "atlas_facts.json"
DIGEST = BACKEND / "data" / "content_digest.baseline.json"

OBSERVED_TIERS = ("measured", "perturbation")


def rows(conn, sql, params=()):
    cur = conn.execute(sql, params)
    cols = [d[0] for d in cur.description]
    return [dict(zip(cols, r)) for r in cur.fetchall()]


def collect(conn) -> dict:
    facts = {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "observed_tiers": list(OBSERVED_TIERS),
    }
    facts["totals"] = rows(conn, """
        SELECT (SELECT COUNT(*) FROM genes) AS genes,
               (SELECT COUNT(*) FROM interactions) AS interactions""")[0]
    facts["sign_evidence_tiers"] = rows(conn, """
        SELECT COALESCE(sign_evidence,'(null)') AS tier, COUNT(*) AS edges
        FROM interactions GROUP BY sign_evidence ORDER BY edges DESC, tier""")
    facts["per_species"] = rows(conn, """
        SELECT g.species AS species,
               COUNT(DISTINCT g.id) AS genes,
               SUM(CASE WHEN i.source_id IS NOT NULL THEN 1 ELSE 0 END) AS edges
        FROM genes g LEFT JOIN interactions i ON i.source_id = g.id
        GROUP BY g.species ORDER BY edges DESC""")
    facts["signed_by_species"] = rows(conn, """
        SELECT g.species AS species, i.sign_evidence AS tier, COUNT(*) AS edges
        FROM interactions i, genes g
        WHERE g.id = i.source_id AND i.sign IS NOT NULL
          AND i.sign_evidence IS NOT NULL AND i.sign_evidence <> 'unknown'
        GROUP BY g.species, i.sign_evidence ORDER BY species, edges DESC""")
    try:
        facts["calibration_gates"] = rows(conn, """
            SELECT species, relation_type, cases, precision, gate_pass
            FROM perturbation_sign_calibration ORDER BY species, relation_type""")
    except sqlite3.Error:
        facts["calibration_gates"] = []
    try:
        facts["multilayer_edges"] = rows(conn, """
            SELECT species, regulatory_layer, COUNT(*) AS edges
            FROM regulatory_layer_edges GROUP BY species, regulatory_layer
            ORDER BY edges DESC""")
    except sqlite3.Error:
        facts["multilayer_edges"] = []
    if DIGEST.exists():
        d = json.loads(DIGEST.read_text())
        facts["content_digest"] = {
            "core": d.get("core_digest"), "atlas": d.get("atlas_digest"),
            "generated_at": d.get("generated_at"),
        }
    return facts


def signed_total(facts) -> int:
    return sum(r["edges"] for r in facts["sign_evidence_tiers"]
               if r["tier"] not in ("unknown", "(null)"))


def observed_total(facts) -> int:
    return sum(r["edges"] for r in facts["sign_evidence_tiers"]
               if r["tier"] in OBSERVED_TIERS)


def to_markdown(facts) -> str:
    t = facts["totals"]
    signed, observed = signed_total(facts), observed_total(facts)
    L = [
        "# Atlas facts",
        "",
        "<!-- GENERATED by backend/scripts/report_atlas_facts.py - do not edit by hand. -->",
        "",
        f"As of {facts['generated_at'][:10]}.",
        "",
        f"- **{t['genes']:,}** genes, **{t['interactions']:,}** interactions",
        f"- **{signed:,}** carry a sign ({signed / t['interactions']:.1%} of the atlas)",
        f"- **{observed:,}** are in the observed signed graph that analysis reasons over",
        "",
        "Most interactions carry no sign because most evidence is binding or",
        "occupancy, which records that a TF binds a promoter, not whether it",
        "activates or represses. That share is a property of the evidence, not a",
        "gap to be closed.",
        "",
        "## Sign evidence tiers",
        "",
        "| Tier | Edges | In the observed graph |",
        "| --- | ---: | --- |",
    ]
    for r in facts["sign_evidence_tiers"]:
        inc = "yes" if r["tier"] in OBSERVED_TIERS else "no"
        L.append(f"| `{r['tier']}` | {r['edges']:,} | {inc} |")

    L += ["", "## Per species", "",
          "| Species | Genes | Interactions |", "| --- | ---: | ---: |"]
    for r in facts["per_species"]:
        L.append(f"| {r['species']} | {r['genes']:,} | {r['edges']:,} |")

    if facts["signed_by_species"]:
        L += ["", "## Signed edges by species and tier", "",
              "| Species | Tier | Edges |", "| --- | --- | ---: |"]
        for r in facts["signed_by_species"]:
            L.append(f"| {r['species']} | `{r['tier']}` | {r['edges']:,} |")

    if facts["calibration_gates"]:
        L += ["", "## Perturbation sign calibration", "",
              "Only a class that passes its gate contributes signs to the observed",
              "graph; the rest sit on `perturbation_exploratory`.", "",
              "| Species | Class | Cases | Precision | Gate |",
              "| --- | --- | ---: | ---: | --- |"]
        for r in facts["calibration_gates"]:
            L.append(f"| {r['species']} | {r['relation_type']} | {r['cases']:,} | "
                     f"{r['precision']:.3f} | {'pass' if r['gate_pass'] else 'fail'} |")

    if facts["multilayer_edges"]:
        L += ["", "## Non-transcriptional layer", "",
              "Curated causal edges that are not transcription. Excluded from the",
              "observed graph; available via `--include-multilayer`.", "",
              "| Species | Layer | Edges |", "| --- | --- | ---: |"]
        for r in facts["multilayer_edges"]:
            L.append(f"| {r['species']} | {r['regulatory_layer']} | {r['edges']:,} |")

    if facts.get("content_digest", {}).get("core"):
        L += ["", "## Build identity", "",
              f"Core content digest `{facts['content_digest']['core']}`",
              "",
              "Two builds asserting the same biology share this digest. See",
              "`backend/scripts/content_digest.py`."]
    return "\n".join(L) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--db", type=Path, default=DB)
    ap.add_argument("--markdown", type=Path, default=MD)
    ap.add_argument("--json", dest="json_out", type=Path, default=JSON_OUT)
    ap.add_argument("--emit-floors", action="store_true",
                    help="print release floors at 90%% of current counts, for "
                         "review before pasting into verify_release_data.py")
    args = ap.parse_args()

    if not args.db.exists():
        print(f"database missing: {args.db}", file=sys.stderr)
        return 1

    conn = sqlite3.connect(f"file:{args.db}?mode=ro", uri=True)
    facts = collect(conn)
    conn.close()

    args.json_out.parent.mkdir(parents=True, exist_ok=True)
    args.json_out.write_text(json.dumps(facts, indent=2) + "\n")
    args.markdown.parent.mkdir(parents=True, exist_ok=True)
    args.markdown.write_text(to_markdown(facts))

    t = facts["totals"]
    print(f"genes {t['genes']:,}   interactions {t['interactions']:,}   "
          f"signed {signed_total(facts):,}   observed {observed_total(facts):,}")
    print(f"markdown: {args.markdown}")
    print(f"json:     {args.json_out}")

    if args.emit_floors:
        print("\nsuggested release floors (90% of current) - review before use:")
        print(f'    "genes": {int(t["genes"] * 0.9):,}'.replace(",", "_"))
        print(f'    "interactions": {int(t["interactions"] * 0.9):,}'.replace(",", "_"))
        for r in facts["sign_evidence_tiers"]:
            if r["tier"] in ("unknown", "(null)"):
                continue
            print(f'    "{r["tier"]}": {int(r["edges"] * 0.9):,}'.replace(",", "_"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
